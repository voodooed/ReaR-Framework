def rank_vod(adapter, ids, cache, seed_base, head=None):
    """Score every frame. Reuses the quantitative run's cached collection when
    it matches, so ranking costs nothing; otherwise regenerates."""
    rows = []
    if cache and Path(cache).exists():
        print(f"  ranking from cached collection {Path(cache).name}")
        z = np.load(cache, allow_pickle=True)
        gxyz, gfr = z["gen_xyz"], z["gen_frame"]
        rxyz, rfr = z["real_xyz"], z["real_frame"]
        keep = np.abs(z["real_az"]) <= adapter.radar_fov_degrees
        rxyz, rfr = rxyz[keep], rfr[keep]
        for i in range(int(z["meta_n_frames"])):
            G, R = gxyz[gfr == i], rxyz[rfr == i]
            if len(G) < MIN_PTS or len(R) < MIN_PTS:
                continue
            s = overlap_scores(G, R)
            s.update(i=i, frame_id=str(ids[i]), seed=seed_base + i,
                     n_gen=int(len(G)), n_real=int(len(R)))
            rows.append(s)
    else:
        print("  no cache -- generating every frame to rank (slow)")
        for i, fid in enumerate(ids):
            fr = adapter.load_frame(fid)
            g = generate_for_frame(adapter, fr, seed=seed_base + i,
                                   architecture=head,
                                   material_device=MATERIAL_DEVICE)
            T = fr.calibration.get("radar_to_lidar")
            o = (np.asarray(T)[:3, 3] if T is not None
                 else np.asarray(adapter.radar_mount_offset, float))
            R = adapter.radar_xyz_in_lidar(fr)
            az = np.degrees(np.arctan2(R[:, 1] - o[1], R[:, 0] - o[0]))
            R = R[np.abs(az) <= adapter.radar_fov_degrees]
            if len(g.points) < MIN_PTS or len(R) < MIN_PTS:
                continue
            s = overlap_scores(g.points[:, :3], R)
            s.update(i=i, frame_id=str(fid), seed=seed_base + i,
                     n_gen=int(len(g.points)), n_real=int(len(R)))
            rows.append(s)
            if (i + 1) % 50 == 0:
                print(f"    {i + 1}/{len(ids)}", flush=True)
    return rows


def render_vod(adapter, frame_id, seed, R, out_png, real_bin, gen_bin,
               no_clutter=False, head=None):
    frame = adapter.load_frame(frame_id)
    gen = generate_for_frame(adapter, frame, seed=seed, architecture=head,
                             material_device=MATERIAL_DEVICE)
    boxes = frame.boxes or []
    T = frame.calibration.get("radar_to_lidar")
    origin = (np.asarray(T)[:3, 3] if T is not None
              else np.asarray(adapter.radar_mount_offset, float))
    fov = adapter.radar_fov_degrees

    rcs_i, vr_i = radar_cols(adapter)
    real_xyz = adapter.radar_xyz_in_lidar(frame)
    real_rcs = frame.radar[:, rcs_i].astype(float)
    real_vr = frame.radar[:, vr_i].astype(float)
    az = np.degrees(np.arctan2(real_xyz[:, 1] - origin[1], real_xyz[:, 0] - origin[0]))
    k = np.abs(az) <= fov
    real_xyz, real_rcs, real_vr = real_xyz[k], real_rcs[k], real_vr[k]

    if no_clutter:
        # Real radar arrives UNLABELLED -- no detection is stamped "multipath".
        # Which real returns are clutter is DERIVED, by the rule the clutter
        # process was fitted with (scripts/fit_dataset.py stage_clutter): a
        # detection with no LiDAR-derived candidate inside the fitted
        # association cone is not explained by any visible surface.
        from _fit_common import candidates_for_frame, operating_point
        from rear.geometry.association import cone_match
        tol, ang = operating_point(adapter)
        cand, _, _ = candidates_for_frame(adapter, frame)
        m, _ = (cone_match(real_xyz, cand.centres, origin, tol, ang)
                if len(cand.centres) and len(real_xyz)
                else (np.zeros(len(real_xyz), bool), None))
        real_xyz, real_rcs, real_vr = real_xyz[m], real_rcs[m], real_vr[m]
        # Generated clutter is sampled LAST inside generate_radar_frame, after
        # every surface draw, so dropping it leaves the surface points
        # bit-for-bit identical to the with-clutter render at the same seed.
        gen = gen._replace(points=gen.points[~gen.is_clutter],
                           is_clutter=gen.is_clutter[~gen.is_clutter])

    g = gen.points
    np.column_stack([real_xyz, real_rcs, real_vr]).astype(np.float32).tofile(real_bin)
    g.astype(np.float32).tofile(gen_bin)
    # Scored on what is actually plotted, so the figure's number always
    # describes the figure.
    score = overlap_scores(g[:, :3], real_xyz)

    both = np.concatenate([real_rcs, g[:, 3]]) if len(real_rcs) or len(g) else np.zeros(1)
    lo, hi = np.percentile(both, [2, 98])

    fig, axes = plt.subplots(1, 4, figsize=(23.5, 6.4), sharex=True, sharey=True)
    ax_l, ax_r, ax_g, ax_o = axes

    # 1 -- LiDAR by intensity (VoD column 3 is intensity)
    lid = frame.lidar
    inten = lid[:, 3].astype(float)
    vmax = float(np.percentile(inten, 99)) if len(inten) else 1.0
    s0 = ax_l.scatter(lid[:, 0], lid[:, 1], c=inten, cmap="cividis", s=0.4,
                      alpha=0.55, vmin=float(np.percentile(inten, 1)), vmax=vmax)
    _draw_boxes(ax_l, boxes)
    ax_l.set_title(f"LiDAR — intensity  ({len(lid):,} pts)")
    fig.colorbar(s0, ax=ax_l, shrink=0.72, label="intensity")

    # 2 / 3 -- real and generated RCS on ONE shared scale
    for ax, xyz, rcs, name in ((ax_r, real_xyz, real_rcs, "REAL"),
                                (ax_g, g[:, :3], g[:, 3], "GENERATED")):
        if len(xyz):
            sc = ax.scatter(xyz[:, 0], xyz[:, 1], c=rcs, cmap="inferno", s=17,
                            edgecolors="k", linewidths=0.2, vmin=lo, vmax=hi, zorder=3)
            fig.colorbar(sc, ax=ax, shrink=0.72, label="RCS (dBsm)")
        _draw_boxes(ax, boxes)
        _draw_fov(ax, origin, fov, R); _draw_rings(ax, origin, R)
        ax.set_title(f"{name} radar — RCS  ({len(xyz)} pts)")

    # 4 -- overlay
    if len(real_xyz):
        ax_o.scatter(real_xyz[:, 0], real_xyz[:, 1], facecolors="none",
                     edgecolors="tab:blue", s=36, linewidths=1.0,
                     label=f"real ({len(real_xyz)})", zorder=3)
    if len(g):
        ax_o.scatter(g[:, 0], g[:, 1], c="tab:orange", marker="x", s=24,
                     linewidths=1.0, label=f"generated ({len(g)})", zorder=4)
    _draw_boxes(ax_o, boxes)
    _draw_fov(ax_o, origin, fov, R); _draw_rings(ax_o, origin, R)
    ax_o.legend(loc="upper right", fontsize=8)
    ax_o.set_title(f"overlay — real vs generated   "
                   f"(F1@{TAU_M:g} m = {score['f1']:.3f})")

    _finish(axes, origin, R, frame.ego_velocity)
    speed = float(np.linalg.norm(frame.ego_velocity))
    fig.suptitle(
        f"{adapter.name} / {frame_id}   (seed={seed})   "
        f"real {len(real_xyz)} pts vs generated {len(g)} pts   |   "
        f"precision {score['prec']:.3f} · recall {score['rec']:.3f} · "
        f"F1 {score['f1']:.3f} @ {TAU_M:g} m   |   ego speed {speed:.1f} m/s",
        fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig(out_png, dpi=140)
    plt.close(fig)

    return dict(frame_id=str(frame_id), seed=int(seed), n_lidar=int(len(lid)),
                n_boxes=len(boxes), n_real=int(len(real_xyz)), n_gen=int(len(g)),
                ego_speed=speed, **{k: float(score[k]) for k in
                                    ("prec", "rec", "f1", "chamfer")})


