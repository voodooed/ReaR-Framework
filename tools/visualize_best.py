# KITTI-CARLA -- rank by scene correspondence
# ===========================================================================
def _in_box(pts, b, margin=0.5):
    if len(pts) == 0:
        return np.zeros(0, bool)
    d = np.asarray(pts)[:, :3] - np.array([b.x, b.y, b.z])
    c, s = np.cos(-b.rotation_z), np.sin(-b.rotation_z)
    lx, ly = d[:, 0] * c - d[:, 1] * s, d[:, 0] * s + d[:, 1] * c
    return ((np.abs(lx) <= b.length / 2 + margin)
            & (np.abs(ly) <= b.width / 2 + margin)
            & (np.abs(d[:, 2]) <= b.height / 2 + margin))


def score_kc_frame(adapter, frame_id, seed, fov, head=None):
    frame = adapter.load_frame(frame_id)
    boxes = adapter.boxes_for(frame_id)
    origin = np.asarray(adapter.radar_mount_offset, float)
    inf = [b for b in boxes
           if abs(np.degrees(np.arctan2(b.y - origin[1], b.x - origin[0]))) <= fov]
    if len(inf) < KC_MIN_OBJECTS:
        return None
    gen = generate_for_frame(adapter, frame, seed=seed, architecture=head,
                             material_device=MATERIAL_DEVICE)
    p = gen.points
    if len(p) < MIN_PTS:
        return None
    hits = sum(1 for b in inf if _in_box(p[:, :3], b).any())
    surf = int((~gen.is_clutter).sum())
    return dict(frame_id=str(frame_id), seed=int(seed), n_obj_fov=len(inf),
                n_hit=hits, hit_rate=hits / len(inf), n_gen=int(len(p)),
                surf_frac=surf / max(len(p), 1), n_lidar=int(len(frame.lidar)),
                n_boxes=len(boxes))


def render_kc(adapter, frame_id, seed, R, out_png, gen_bin, score,
              no_clutter=False, head=None):
    frame = adapter.load_frame(frame_id)
    boxes = adapter.boxes_for(frame_id)
    gen = generate_for_frame(adapter, frame, seed=seed, architecture=head,
                             material_device=MATERIAL_DEVICE)
    p, is_cl = gen.points, gen.is_clutter
    if no_clutter:
        # Clutter is drawn last, so the surface stream is unchanged by this.
        p, is_cl = p[~is_cl], is_cl[~is_cl]
    p.astype(np.float32).tofile(gen_bin)
    origin = np.asarray(adapter.radar_mount_offset, float)
    fov = adapter.radar_fov_degrees

    surf = p[~is_cl]
    tree = cKDTree(frame.lidar[:, :3])
    if len(surf):
        nnd, nni = tree.query(surf[:, :3], k=1)
        tags = frame.lidar_semantic[nni]
    else:
        nnd, tags = np.zeros(0), np.zeros(0, int)

    fig, axes = plt.subplots(1, 4, figsize=(23.5, 6.4), sharex=True, sharey=True)
    ax_l, ax_s, ax_r, ax_c = axes
    lid = frame.lidar

    # 1 -- KITTI-CARLA ships no intensity; column 3 is the LiDAR incidence
    # cosine, which is the reflectance-like channel this dataset does provide.
    # Labelled for what it is rather than passed off as intensity.
    cos = lid[:, 3].astype(float)
    s0 = ax_l.scatter(lid[:, 0], lid[:, 1], c=cos, cmap="cividis", s=0.4,
                      alpha=0.55, vmin=0.0, vmax=1.0)
    _draw_boxes(ax_l, boxes)
    ax_l.set_title(f"LiDAR — incidence cosine  ({len(lid):,} pts)")
    fig.colorbar(s0, ax=ax_l, shrink=0.72, label="cos(incidence)")

    # 2 -- semantic class
    present = np.unique(frame.lidar_semantic)
    for t in present:
        m = frame.lidar_semantic == t
        ax_s.scatter(lid[m, 0], lid[m, 1], c=CATEGORY_COLOR.get(int(t), "gray"),
                     s=0.4, alpha=0.6, zorder=2)
    _draw_boxes(ax_s, boxes)
    ax_s.set_title("LiDAR — CARLA semantic class")
    ax_s.legend(handles=[Line2D([0], [0], marker="o", color="w", markersize=5,
                                markerfacecolor=CATEGORY_COLOR.get(int(t), "gray"),
                                label=CARLA_TAGS.get(int(t), f"tag{int(t)}"))
                         for t in present],
                loc="upper right", fontsize=5.5, ncol=2, framealpha=0.9)

    # 3 -- generated radar, RCS
    clut = p[is_cl]
    if len(clut):
        ax_r.scatter(clut[:, 0], clut[:, 1], c="0.75", s=10, marker="x",
                     label=f"clutter ({len(clut)})", zorder=2)
    if len(surf):
        # Neutral wording when there is no second stream to contrast against.
        sc = ax_r.scatter(surf[:, 0], surf[:, 1], c=surf[:, 3], cmap="inferno",
                          s=17, edgecolors="k", linewidths=0.2,
                          label=(f"surface ({len(surf)})" if len(clut)
                                 else f"generated ({len(surf)})"), zorder=3)
        fig.colorbar(sc, ax=ax_r, shrink=0.72, label="RCS (dBsm)")
    _draw_boxes(ax_r, boxes)
    _draw_fov(ax_r, origin, fov, R); _draw_rings(ax_r, origin, R)
    ax_r.legend(loc="upper right", fontsize=7)
    ax_r.set_title(f"GENERATED radar — RCS  ({len(p)} pts)")

    # 4 -- generated radar, coloured by the source object each return came from
    if len(clut):
        ax_c.scatter(clut[:, 0], clut[:, 1], c="0.75", s=10, marker="x", zorder=2)
    if len(surf):
        rcs = surf[:, 3]
        span = max(rcs.max() - rcs.min(), 1e-6)
        ax_c.scatter(surf[:, 0], surf[:, 1],
                     c=[CATEGORY_COLOR.get(int(t), "gray") for t in tags],
                     s=10 + (rcs - rcs.min()) / span * 50,
                     edgecolors="k", linewidths=0.3, zorder=3)
    _draw_boxes(ax_c, boxes)
    _draw_fov(ax_c, origin, fov, R); _draw_rings(ax_c, origin, R)
    hs = [Line2D([0], [0], marker="o", color="w", markersize=6,
                 markerfacecolor=CATEGORY_COLOR.get(t, "gray"),
                 label=CARLA_TAGS.get(t, f"tag{t}"))
          for t in sorted(set(int(t) for t in tags))]
    if len(clut):
        hs.append(Line2D([0], [0], marker="x", color="0.6", linestyle="None",
                         markersize=6, label="clutter (no LiDAR match)"))
    ax_c.legend(handles=hs, loc="upper right", fontsize=6)
    ax_c.set_title("GENERATED radar — source object class  (size = RCS)")

    _finish(axes, origin, R, frame.ego_velocity)
    speed = float(np.hypot(frame.ego_velocity[0], frame.ego_velocity[1]))
    # Composition and hit count both describe what is actually plotted, so a
    # render without the clutter stream reports its own point count and its
    # own hit count rather than inheriting the ranking pass's numbers.
    comp = (f" ({len(surf)} surface + {len(clut)} clutter)" if len(clut) else "")
    inf = [b for b in boxes
           if abs(np.degrees(np.arctan2(b.y - origin[1], b.x - origin[0]))) <= fov]
    n_hit = sum(1 for b in inf if _in_box(p[:, :3], b).any())
    fig.suptitle(
        f"{adapter.name} / {frame_id}   (seed={seed})   "
        f"{len(p)} generated pts{comp}   |   "
        f"objects in FOV hit: {n_hit}/{len(inf)}   |   "
        f"mean source-match {nnd.mean() if len(nnd) else float('nan'):.2f} m   |   "
        f"ego speed {speed:.1f} m/s", fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig(out_png, dpi=140)
    plt.close(fig)

    r = dict(score)
    # Frame facts are re-derived here rather than inherited, so a render driven
    # from a preset selection carries the same fields as a ranked one.
    r.update(frame_id=str(frame_id), seed=int(seed), n_lidar=int(len(frame.lidar)),
             n_boxes=len(boxes), n_gen=int(len(p)), n_surface=int(len(surf)),
             n_clutter=int(len(clut)), n_hit=n_hit, n_obj_fov=len(inf),
             hit_rate=n_hit / max(len(inf), 1),
             surf_frac=len(surf) / max(len(p), 1),
             mean_nn_dist=float(nnd.mean()) if len(nnd) else float("nan"),
             ego_speed=speed)
    return r


# ===========================================================================
def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", required=True, choices=["vod", "kitti_carla"])
    ap.add_argument("--n", type=int, default=10)
    ap.add_argument("--split", default=None, help="vod: split to rank (default test)")
    ap.add_argument("--seed", type=int, default=0,
                    help="base seed; VoD uses seed+frame_index to match the "
                         "quantitative cache, KITTI-CARLA uses it directly")
    ap.add_argument("--range", type=float, default=60.0)
    ap.add_argument("--material-device", default="cuda",
                    help="where a segmentation model runs when the dataset "
                         "needs one to build the material block")
    ap.add_argument("--separation", type=int, default=MIN_SEPARATION)
    ap.add_argument("--scan", type=int, default=400,
                    help="kitti_carla: how many frames to score before picking")
    ap.add_argument("--cache", default=None,
                    help="the collection evaluate_quantitative.py cached, so "
                         "ranking costs nothing. Either the .npz itself or the "
                         "DIRECTORY holding it -- the head-specific file is "
                         "resolved from --head/--seed/--split, because reusing "
                         "another head's collection would rank this head's "
                         "frames by a different model's output.")
    ap.add_argument("--out", default=None)
    ap.add_argument("--head", default=None, choices=available_architectures(),
                    help="override fitted.heads.implementation for this run")
    ap.add_argument("--no-clutter", action="store_true",
                    help="plot and write only the surface-origin stream. For VoD "
                         "this drops BOTH the generated clutter and the real "
                         "detections no LiDAR surface explains, so the two sides "
                         "stay like-for-like. The figures carry no annotation "
                         "about this.")
    ap.add_argument("--from-selection", default=None, metavar="FRAMES_JSON",
                    help="skip ranking and re-render exactly the (frame_id, seed) "
                         "pairs recorded in a previous run's frames.json -- how "
                         "the clutter-free variant is kept on the same frames as "
                         "the set it mirrors.")
    args = ap.parse_args()
    global MATERIAL_DEVICE
    MATERIAL_DEVICE = args.material_device

    out = Path(args.out or REPO_ROOT / "output" / "qualitative" / args.dataset)
    if out.exists():
        shutil.rmtree(out)
    (out / "viz").mkdir(parents=True)
    (out / "radar_bin").mkdir()

    preset = None
    if args.from_selection:
        preset = json.loads(Path(args.from_selection).read_text())
        print(f"re-rendering the {len(preset)} frames recorded in "
              f"{Path(args.from_selection).name} (no re-ranking)")

    if args.dataset == "vod":
        split = args.split or "test"
        adapter = load_adapter("vod", split=split)
        (out / "real_bin").mkdir()
        ids = adapter.sequence_splits()[split]
        if preset:
            sel = [dict(frame_id=p["frame_id"], seed=p["seed"],
                        f1_percentile=p.get("f1_percentile")) for p in preset]
            f1 = None
        else:
            print(f"ranking {len(ids)} {split} frames by real<->generated BEV overlap "
                  f"(F1 @ {TAU_M:g} m)")
            rows = rank_vod(adapter, ids, _resolve_cache(args, split, len(ids)),
                            args.seed, args.head)
            sel = pick_diverse(rows, args.n, "f1", args.separation)
            f1 = np.array([r["f1"] for r in rows])
            print(f"  scored {len(rows)} frames -- F1 median {np.median(f1):.3f}, "
                  f"max {f1.max():.3f}")
            print(f"  selected {len(sel)} (>= {args.separation} frames apart):")
        print(f"\n  {'rank':>4}{'frame':>10}{'real':>7}{'gen':>7}"
              f"{'prec':>8}{'recall':>8}{'F1':>8}{'chamfer':>9}")
        chosen = []
        for k, s in enumerate(sel, 1):
            safe = s["frame_id"].replace(":", "_")
            r = render_vod(adapter, s["frame_id"], s["seed"], args.range,
                           out / "viz" / f"viz_{safe}.png",
                           out / "real_bin" / f"{safe}.bin",
                           out / "radar_bin" / f"{safe}.bin",
                           no_clutter=args.no_clutter, head=args.head)
            print(f"  {k:>4}{r['frame_id']:>10}{r['n_real']:>7}{r['n_gen']:>7}"
                  f"{r['prec']:>8.3f}{r['rec']:>8.3f}{r['f1']:>8.3f}{r['chamfer']:>9.2f}")
            r["rank"] = k
            if f1 is not None:
                r["f1_percentile"] = 100.0 * (f1 < s["f1"]).mean()
            elif s.get("f1_percentile") is not None:
                # carried from the set this one mirrors: the frames were chosen
                # there, so the percentile describes that selection, not this render
                r["f1_percentile_of_source_selection"] = s["f1_percentile"]
            chosen.append(r)
    else:
        adapter = load_adapter("kitti_carla")
        fov = adapter.radar_fov_degrees
        if preset:
            sel = [dict(frame_id=p["frame_id"], seed=p["seed"],
                        n_obj_fov=p.get("n_obj_fov", 0), n_hit=p.get("n_hit", 0),
                        hit_rate=p.get("hit_rate", 0.0),
                        surf_frac=p.get("surf_frac", 0.0),
                        n_gen=p.get("n_gen", 0)) for p in preset]
        else:
            splits = adapter.sequence_splits()
            pool = [(t, fid) for t in splits for fid in splits[t]]
            step = max(len(pool) // args.scan, 1)
            scan = pool[::step][:args.scan]
            print(f"scoring {len(scan)} KITTI-CARLA frames (of {len(pool)}) by "
                  f"in-FOV object hit rate")
            rows = []
            for j, (_, fid) in enumerate(scan):
                s = score_kc_frame(adapter, fid, args.seed, fov, args.head)
                if s:
                    s["i"] = j * step
                    rows.append(s)
                if (j + 1) % 50 == 0:
                    print(f"    {j + 1}/{len(scan)}  (kept {len(rows)})", flush=True)
            if not rows:
                raise SystemExit("no frame met the minimum-object criterion")
            # rank by hit rate, then richer scenes, then more geometry-derived points
            for r in rows:
                r["rankkey"] = (r["hit_rate"] + 1e-3 * r["n_obj_fov"]
                                + 1e-6 * r["surf_frac"])
            sel = pick_diverse(rows, args.n, "rankkey", args.separation * step)
            hr = np.array([r["hit_rate"] for r in rows])
            print(f"  scored {len(rows)} eligible frames -- hit-rate median "
                  f"{np.median(hr):.3f}, max {hr.max():.3f}")
            print(f"  selected {len(sel)}:")
        print(f"\n  {'rank':>4}{'frame':>14}{'objFOV':>8}{'hit':>6}{'hit%':>8}"
              f"{'gen':>7}{'surf%':>8}")
        chosen = []
        for k, s in enumerate(sel, 1):
            safe = s["frame_id"].replace(":", "_")
            r = render_kc(adapter, s["frame_id"], s["seed"], args.range,
                          out / "viz" / f"viz_{safe}.png",
                          out / "radar_bin" / f"{safe}.bin", s,
                          no_clutter=args.no_clutter, head=args.head)
            print(f"  {k:>4}{r['frame_id']:>14}{r['n_obj_fov']:>8}{r['n_hit']:>6}"
                  f"{100*r['hit_rate']:>7.1f}%{r['n_gen']:>7}"
                  f"{100*r['n_surface']/max(r['n_gen'],1):>7.1f}%")
            r["rank"] = k
            r.pop("rankkey", None)
            r.pop("i", None)
            chosen.append(r)

    (out / "frames.json").write_text(json.dumps(chosen, indent=1))
    print(f"\nwrote {len(chosen)} frames -> {out}")


if __name__ == "__main__":
    main()
