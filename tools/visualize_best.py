#!/usr/bin/env python
"""Select the strongest frames for a dataset and render them as 1x4 BEV rows.

    python tools/visualize_best.py --dataset vod          --n 10 --out output/qualitative/vod
    python tools/visualize_best.py --dataset kitti_carla  --n 10 --out output/qualitative/kitti_carla

Frames are RANKED, never sampled at random. What "best" means is necessarily
different for the two datasets, because only one of them has a ground truth to
be close to:

VoD -- ranked by REAL<->GENERATED AGREEMENT
    Both clouds exist for the same frame, so the criterion is direct overlap.
    For each frame, in the BEV plane the overlay is actually judged in:

        precision = fraction of GENERATED points with a REAL point within TAU
        recall    = fraction of REAL points with a GENERATED point within TAU
        score     = F1 = harmonic mean of the two

    TAU = 1.5 m, roughly one radar resolution cell at mid-range (VoD's azimuth
    resolution alone spans ~1.75 m cross-range at 20 m). Chamfer distance is
    recorded alongside as a threshold-free check that the ranking is not an
    artefact of the cut.

    Ranking is on the FULL clouds, including clutter on both sides -- that is
    what the figure displays, and real radar carries its own ~30% clutter, so
    the comparison stays like-for-like.

KITTI-CARLA -- ranked by SCENE CORRESPONDENCE
    There is no real radar here, so "close to ground truth" cannot mean
    agreement with a reference sweep. The available notion of correctness is
    whether the generated cloud lands on the scene structure that is actually
    there: annotated objects inside the radar FOV should receive returns, and
    surface points should trace real LiDAR geometry. Frames are ranked by the
    fraction of in-FOV annotated objects that receive at least one generated
    detection, restricted to scenes with enough objects to be worth showing.

BOTH are additionally constrained to be SCENE-DIVERSE. The top of an
unconstrained ranking is dominated by consecutive frames -- ~0.1 s apart and
near-duplicates -- which would make ten "best examples" one example shown ten
times. A minimum index separation is enforced greedily down the ranking, which
costs very little score (VoD: 0.763 -> 0.725 over the ten) and buys genuinely
distinct scenes.

LAYOUT -- identical 1x4 horizontal row for both datasets.

    VoD          LiDAR (intensity) | REAL radar | GENERATED radar | overlay
    KITTI-CARLA  LiDAR (incidence) | semantic   | GENERATED (RCS) | GENERATED by source class

Panels 2 and 3 of the VoD row share one RCS colour scale, computed over the
union of both streams; a per-panel autoscale would make two different
distributions look identical, which is the comparison this row exists to make.
"""

