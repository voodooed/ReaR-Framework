def _box_corners_xy(b):
    hl, hw = b.length / 2.0, b.width / 2.0
    local = np.array([[hl, hw], [hl, -hw], [-hl, -hw], [-hl, hw]])
    c, s = np.cos(b.rotation_z), np.sin(b.rotation_z)
    return (local @ np.array([[c, -s], [s, c]]).T) + np.array([b.x, b.y])


def _draw_boxes(ax, boxes, color="blue", label=True):
    for b in boxes:
        p = Polygon(_box_corners_xy(b), closed=True, fill=False,
                    edgecolor=color, linewidth=1.1, zorder=5)
        p.set_clip_on(True)
        ax.add_patch(p)
        if label:
            ax.text(b.x, b.y + b.width / 2.0 + 0.4, b.class_name, color=color,
                    fontsize=5.5, ha="center", zorder=6, clip_on=True)


def _draw_fov(ax, origin, fov_deg, max_range, color="0.6"):
    """`radar_fov_degrees` is a HALF-angle -- the generator keeps candidates
    with |azimuth| <= radar_fov_deg, so 60.0 means a +-60 deg / 120 deg sector."""
    half = np.radians(fov_deg)
    for a in (-half, half):
        ax.plot([origin[0], origin[0] + max_range * np.cos(a)],
                [origin[1], origin[1] + max_range * np.sin(a)],
                color=color, lw=0.8, ls="--", zorder=1)


def _draw_rings(ax, origin, max_range, step=20, color="0.85"):
    for r in np.arange(step, max_range + 1, step):
        ax.add_patch(Circle(origin, r, fill=False, ec=color, lw=0.6, ls=":", zorder=0))


def _finish(axes, origin, R, ego_v):
    for ax in axes:
        ax.set_xlim(origin[0] - 5, origin[0] + R)
        ax.set_ylim(-R, R)
        ax.set_aspect("equal")
        ax.set_xlabel("x (m, forward)")
        ax.plot(*origin[:2], marker="^", color="blue", markersize=7, zorder=6)
        if np.hypot(ego_v[0], ego_v[1]) >= 1e-3:
            ax.annotate("", xy=(origin[0] + ego_v[0] * 1.5, origin[1] + ego_v[1] * 1.5),
                        xytext=origin[:2],
                        arrowprops=dict(arrowstyle="->", color="blue", lw=1.5), zorder=7)
    axes[0].set_ylabel("y (m, left)")


def radar_cols(adapter):
    cols = adapter.config["sensors"].get("radar_columns") or []
    return (cols.index("rcs") if "rcs" in cols else 3,
            cols.index("v_r") if "v_r" in cols else 4)


def overlap_scores(G, R, tau=TAU_M):
    """BEV precision / recall / F1 / Chamfer between two point sets."""
    if len(G) < 1 or len(R) < 1:
        return dict(prec=0.0, rec=0.0, f1=0.0, chamfer=float("inf"))
    g, r = np.asarray(G)[:, :2].astype(float), np.asarray(R)[:, :2].astype(float)
    dg, _ = cKDTree(r).query(g, k=1)
    dr, _ = cKDTree(g).query(r, k=1)
    P, Rc = float((dg <= tau).mean()), float((dr <= tau).mean())
    return dict(prec=P, rec=Rc, f1=(2 * P * Rc / (P + Rc) if P + Rc > 0 else 0.0),
                chamfer=float(dg.mean() + dr.mean()))


def pick_diverse(rows, n, key, sep=MIN_SEPARATION):
    """Greedy top-N down the ranking, keeping selections >= `sep` frames apart."""
    out = []
    for r in sorted(rows, key=lambda x: -x[key]):
        if all(abs(r["i"] - s["i"]) >= sep for s in out):
            out.append(r)
        if len(out) == n:
            break
    return out


def _resolve_cache(args, split, n_ids):
    """The cached collection for THIS head, or None.

    Accepts a file or a directory. Resolving by head is not a convenience: the
    collection is a specific model's generated cloud, so ranking one head's
    frames against another head's collection would silently select frames on
    the wrong evidence.
    """
    if not args.cache:
        return None
    c = Path(args.cache)
    if c.is_dir():
        head = args.head or "prism"
        hits = sorted(c.glob(f"_collected_{split}_*_seed{args.seed}_{head}.npz"))
        if not hits:
            print(f"  no cached collection for head={head!r} in {c} -- "
                  f"generating to rank (slow)")
            return None
        return hits[0]
    return c


